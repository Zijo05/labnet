"""Write an Ansible inventory for a lab.

The inventory uses Ansible's Incus connection plugin instead of SSH. Ansible
then reaches each node the same way ``labnet shell`` does (through
``incus exec``), so playbooks work even on nodes that have no address yet,
and there are no SSH keys or host-key warnings to deal with.
"""

from __future__ import annotations

from labnet.engine import LabState

# Inventory group name for each role.
_GROUPS = {"router": "routers", "server": "servers", "pc": "pcs"}


def inventory_text(lab: LabState) -> str:
    """Return the inventory for ``lab`` in Ansible's INI format."""
    lines = [
        f"# Ansible inventory for the labnet lab '{lab.name}'.",
        f"# Generated by: labnet export ansible {lab.name}",
        "#",
        "# Nodes are reached through Incus, not SSH, so this works even before",
        "# the lab has any addresses. Try it with:",
        f"#   ansible -i <this file> {_group_name(lab.name)} -m ping",
        "",
    ]
    used_groups = []
    for role, group in _GROUPS.items():
        nodes = [node for node in lab.nodes if node.role == role]
        if not nodes:
            continue
        used_groups.append(group)
        lines.append(f"[{group}]")
        # The inventory name is the short node name; ansible_host is the
        # Incus instance name the connection plugin needs.
        lines.extend(f"{node.node} ansible_host={node.instance}" for node in nodes)
        lines.append("")

    lab_group = _group_name(lab.name)
    lines.append(f"[{lab_group}:children]")
    lines.extend(used_groups)
    lines.append("")
    lines.append(f"[{lab_group}:vars]")
    lines.append("ansible_connection=community.general.incus")
    lines.append("ansible_python_interpreter=/usr/bin/python3")
    lines.append("")
    return "\n".join(lines)


def _group_name(lab_name: str) -> str:
    """Ansible group names may not contain hyphens; use underscores instead."""
    return "lab_" + lab_name.replace("-", "_")
